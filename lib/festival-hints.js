export function didMentionFestival(text, festivalName) {
  const terms =
    FESTIVAL_MENTION_TERMS[festivalName] || FESTIVAL_MENTION_TERMS[baseFestivalName(festivalName)];
  if (!terms?.length) return false;
  const visibleText = String(text || "").replace(/<mood>[\s\S]*?<\/mood>/gi, "");
  return terms.some((term) => visibleText.includes(term));
}

// ── 纯逻辑：随机抽取（抽过优先不重复）──
// 不持久化状态，由调用方决定是否传上次抽过的索引。返回 { index, text, nextUsed }。
export function pickFestivalHint(festivalName, usedIndexes = []) {
  const entry = getFestivalHintPool(festivalName);
  if (!entry || !Array.isArray(entry.pool) || entry.pool.length === 0) {
    return null;
  }
  const pool = entry.pool;
  const usedSet = new Set(usedIndexes.filter((i) => Number.isInteger(i) && i >= 0 && i < pool.length));

  // 候选：没用过的优先；全用过了就全部重新可用（轮换一轮）
  let candidates = pool.map((_, i) => i).filter((i) => !usedSet.has(i));
  if (candidates.length === 0) candidates = pool.map((_, i) => i);

  const index = candidates[Math.floor(Math.random() * candidates.length)];
  return {
    index,
    text: pool[index],
    nextUsed: [...usedSet, index],
  };
}
