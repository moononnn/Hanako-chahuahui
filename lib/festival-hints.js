// 「中秋节假期」这类名字回落到节日本名（中秋节）取意象池与问候判定。
function baseFestivalName(name) {
  return String(name || "").replace(/假期$/, "");
}

/**
 * 取某个节日名该用的意象池：节日本名优先，假期名回落到通用假期池。
 * @param {string} name
 * @returns {{pool: string[]}|null}
 */
export function getFestivalHintPool(name) {
  const direct = FESTIVAL_HINTS[name];
  if (direct) return direct;
  if (baseFestivalName(name) !== name) return HOLIDAY_HINTS;
  return null;
}

